  function toProblem(stage, slot) {
    const meta = HS_FLOORS[stage];
    let choices = null;
    if (slot.type === 'choice' && slot.choices) {
      choices = shuf(slot.choices).slice(0, 5);
      if (!choices.includes(slot.ans)) choices[0] = slot.ans;
    }
    return {
      typeId: 'HS_' + stage + '_' + slot.no,
      stage, grade: meta.grade, topic: slot.topic,
      questionText: slot.q, answer: slot.ans, choices,
      inputMode: slot.type, renderType: slot.fig ? 'svg' : 'text',
      svgContent: slot.fig || null, source: slot.source,
      difficulty: slot.d, isSlot: true,
    };
  }

  /* 한 전투 안에서 같은 문항이 연속/반복되지 않도록 셔플된 큐를 stage별로 유지 */
  const _queues = {};
  function _queue(stage) {
    if (!_queues[stage] || _queues[stage].length === 0) {
      const idx = HS_DATA[stage].problems.map((_, i) => i);
      _queues[stage] = shuf(idx);
    }
    return _queues[stage];
  }
  function getHSProblem(stage, idx) {
    const d = HS_DATA[stage]; if (!d) return null;
    const q = _queue(stage);
    const pick = q.shift();
    return toProblem(stage, d.problems[pick]);
  }
  function hsProblemCount(stage) { return (HS_DATA[stage] && HS_DATA[stage].problems.length) || 0; }

  window.HSFloors = { HS_FLOORS, HS_DATA, getHSProblem, hsProblemCount, isHS: s => s >= 21 && s <= 30 };
